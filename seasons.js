//   choices[i].short - short label for the finale's path list
//   choices[i].side  - 0 or 1, the season's `sides`. Hidden from the player.
//
// Legacy finale.endings is picked by how many of the five choices were on side 0:
// the first ending whose `min` the count reaches. "모든 날 반대로 골랐다면"
// flips every choice and keeps every hidden condition, so the count becomes
// 5 - n. If both land on the same ending, `same` is added under it.
// New finale.scenes replay named moments using that day's choice and condition.
// They do not score the player or infer a personality from a count.
//
// Revising a season: give it a new id and `replaces` (one id or a list), and move
